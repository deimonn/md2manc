static void read_file(FILE *instream, char **text_out, size_t *size_out)
{
    size_t size = 0;
    size_t cap = 4096;

    char *text = malloc(cap);

    if (!text) {
        error("failed to allocate memory: %s", strerror(errno));
        exit(1);
    }

    while (!feof(instream) && !ferror(instream)) {
        char buffer[4096];
        size_t bytes = fread(buffer, 1, sizeof(buffer), instream);

        if (size + bytes > cap) {
            cap *= 2;
            text = realloc(text, cap);

            if (!text) {
                error("failed to reallocate memory: %s", strerror(errno));
                exit(1);
            }
        }

        memcpy(text + size, buffer, bytes);
        size += bytes;
    }

    *text_out = text;
    *size_out = size;
}

static void infer_title_and_section(char *path)
{
    char *name = basename(path);
    char *ext = strrchr(name, '.');

    if (!ext || strcmp(ext, ".md") != 0) {
        title = path;
        return;
    }

    *ext = '\0';

    char *sect = strrchr(name, '.');

    if (!sect) {
        title = name;
        return;
    }

    *sect = '\0';
    title = name;
    section = sect + 1;
}

int main(int argc, char **argv)
{
#ifdef _HAS_SIGTRACE
    sigtrace(sigtrace_faults);
#endif

    int inarg = parse_options(argv);
    char *inpath = argv[inarg];

    if (inarg + 1 < argc)
        error("cannot process more than one input file at a time");

    FILE *instream;

    if (inpath) {
        instream = fopen(inpath, "r");

        if (!instream) {
            error("failed to open %s: %s", inpath, strerror(errno));
            exit(1);
        }

        infer_title_and_section(inpath);
    } else {
        instream = stdin;
    }

    char *input;
    size_t size;

    read_file(instream, &input, &size);
    fclose(instream);

    int result = convert_markdown(input, size);

    free(input);

    return result == -1 ? 1 : 0;
}
