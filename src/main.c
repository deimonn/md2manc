// *INDENT-OFF*
static const char *const usage =
    "Usage: %s [OPTION...] [FILE]\n"
    "Options:\n"
    "  -h, --help    print this text\n"
    "  --version     print program version\n"
    "\n"
    "  -t TITLE      set man page title\n"
    "  -s SECTION    set man page section number\n"
    "  -d DATE       set man page center footer (last change date)\n"
    "  -S SOURCE     set man page left footer (project name and version)\n"
    "  -V VOLUME     set man page center header (section name)\n"
    "\n"
    "  --no-comment  do not output 'generated by' roff comment\n"
    "\n"
    "If FILE is '-' or omitted, reads from standard input\n"
    "\n"
    "If FILE is a filename, TITLE and SECTION can be inferred from it\n"
    "\n"
    "See md2manc(1) for details\n";
// *INDENT-ON*

static const char *const version = "md2manc version %s\n";

static void print_usage_and_exit(char *argv0)
{
    printf(usage, argv0);
    exit(0);
}

static void print_version_and_exit(void)
{
    printf(version, _PROGRAM_VERSION);
    exit(0);
}

static const char *title = NULL;
static const char *section = NULL;
static const char *date = "";
static const char *source = "";
static const char *volume = NULL;

static bool print_generated_by_comment = true;

static int parse_options(int argc, char **argv)
{
    for (;;) {
        switch (getopt(argc, argv, ":-:ht:s:d:S:V:")) {
        case '-':
            if (strcmp(optarg, "help") == 0)
                print_usage_and_exit(argv[0]);

            if (strcmp(optarg, "version") == 0)
                print_version_and_exit();

            if (strcmp(optarg, "no-comment") == 0) {
                print_generated_by_comment = false;
                continue;
            }

            error("unknown option '--%s'", optarg);
            exit(2);
        case 'h':
            print_usage_and_exit(argv[0]);
            continue;
        case 't':
            title = optarg;
            continue;
        case 's':
            section = optarg;
            continue;
        case 'd':
            date = optarg;
            continue;
        case 'S':
            source = optarg;
            continue;
        case 'V':
            volume = optarg;
            continue;
        case ':':
            error("missing argument for option '-%c'", optopt);
            exit(2);
        case '?':
            error("unknown option '-%c'", optopt);
            exit(2);
        default:
            return optind;
        }
    }
}

