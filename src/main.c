static int print_document_header(void)
{
    if (!title)
        title = "UNTITLED";
    if (!section)
        section = "1";

    char *uptitle = strdup(title);

    if (!uptitle)
        error("out of memory");

    for (char *cur = uptitle; *cur; cur++)
        *cur = toupper(*cur);

    if (print_generated_by_comment)
        printf(".\\\" automatically generated by md2manc %s\n",
               _PROGRAM_VERSION);

    printf(".TH \"%s\" %s \"%s\" \"%s\"", uptitle, section, date, source);

    if (volume)
        printf(" \"%s\"", volume);

    printf("\n.nh\n");
    printf(".ad l\n");

    free(uptitle);
    return 0;
}

static int enter_block(MD_BLOCKTYPE type, void *detail, void *userdata)
{
    (void)userdata;

    switch (type) {
    case MD_BLOCK_DOC:
        return 0;
    case MD_BLOCK_QUOTE:
        return enter_block_quote();
    case MD_BLOCK_UL:
        return enter_unordered_list(detail);
    case MD_BLOCK_OL:
        return enter_ordered_list(detail);
    case MD_BLOCK_LI:
        return enter_list_item();
    case MD_BLOCK_HR:
        return warning("ignoring thematic break (---, ***, ___)");
    case MD_BLOCK_H:
        return enter_heading(detail);
    case MD_BLOCK_CODE:
        return enter_code_block(detail);
    case MD_BLOCK_P:
        return enter_paragraph();
    default:
        assert(!"unhandled block type");
    }
}

static int leave_block(MD_BLOCKTYPE type, void *detail, void *userdata)
{
    (void)detail;
    (void)userdata;

    switch (type) {
    case MD_BLOCK_DOC:
        return 0;
    case MD_BLOCK_QUOTE:
        return leave_block_quote();
    case MD_BLOCK_UL:
        return leave_unordered_list();
    case MD_BLOCK_OL:
        return leave_ordered_list();
    case MD_BLOCK_LI:
        return leave_list_item();
    case MD_BLOCK_HR:
        return 0;
    case MD_BLOCK_H:
        return leave_heading();
    case MD_BLOCK_CODE:
        return leave_code_block();
    case MD_BLOCK_P:
        return leave_paragraph();
    default:
        assert(!"unhandled block type");
    }
}

static int enter_span(MD_SPANTYPE type, void *detail, void *userdata)
{
    (void)userdata;

    switch (type) {
    case MD_SPAN_EM:
        return enter_emphasis();
    case MD_SPAN_STRONG:
        return enter_strong();
    case MD_SPAN_A:
        return enter_link(detail);
    case MD_SPAN_IMG:
        return enter_image();
    case MD_SPAN_CODE:
        return 0;
    default:
        assert(!"unhandled span type");
    }
}

static int leave_span(MD_SPANTYPE type, void *detail, void *userdata)
{
    (void)detail;
    (void)userdata;

    switch (type) {
    case MD_SPAN_EM:
        return leave_emphasis();
    case MD_SPAN_STRONG:
        return leave_strong();
    case MD_SPAN_A:
        return leave_link();
    case MD_SPAN_IMG:
        return 0;
    case MD_SPAN_CODE:
        return 0;
    default:
        assert(!"unhandled span type");
    }
}

static int text(MD_TEXTTYPE type, const MD_CHAR *text, MD_SIZE size,
                void *userdata)
{
    (void)userdata;

    if (*text_mode == suppress_text)
        return 0;

    switch (type) {
    case MD_TEXT_NORMAL:
        return print_text(text, size);
    case MD_TEXT_NULLCHAR:
        return print_nullchar();
    case MD_TEXT_BR:
        return print_hard_break();
    case MD_TEXT_SOFTBR:
        return print_soft_break();
    case MD_TEXT_ENTITY:
        return print_entity(text, size);
    case MD_TEXT_CODE:
        return print_code(text, size);
    default:
        assert(!"unhandled text type");
    }
}

static const MD_PARSER parser = {
    .flags = MD_FLAG_NOHTML,
    .enter_block = enter_block,
    .leave_block = leave_block,
    .enter_span = enter_span,
    .leave_span = leave_span,
    .text = text
};

static int convert_markdown(const char *text, unsigned int length)
{
    print_document_header();
    return md_parse(text, length, &parser, NULL);
}

